#!/usr/bin/env python3
"""Generates src/pso_names.inc: CodeWalker's MetaName enum (name <-> joaat hash) as a sorted C++ table,
used by pso_name() so dumps print field and structure names.

    python tools/gen_pso_names.py <CodeWalker.Core/GameFiles/MetaTypes> > src/pso_names.inc
"""
import re
import sys

src = open(sys.argv[1] + "/MetaNames.cs", encoding="utf-8-sig").read()
start = src.index("public enum MetaName : uint")
seen = {}
for m in re.finditer(r"^\s*(@?\w+)\s*=\s*(\d+)\s*,", src[start:], re.M):
    name = m.group(1).lstrip("@")
    h = int(m.group(2))
    if name == "null" or h == 0:
        continue
    seen.setdefault(h, name)
print("// generated by tools/gen_pso_names.py from CodeWalker's MetaName enum - do not edit")
print("struct GenName { uint32_t hash; const char* name; };")
print("static const GenName kGenNames[] = {")
for h in sorted(seen):
    print('    {0x%08X, "%s"},' % (h, seen[h]))
print("};")
