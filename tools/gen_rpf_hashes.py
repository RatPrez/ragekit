#!/usr/bin/env python3
"""Generates src/rpf_key_hashes.inc from CodeWalker's GTAKeys.cs: the SHA1 hashes (not keys)
used to find the AES key, NG keys, NG decrypt tables and hash LUT inside the game executable.
Usage: gen_rpf_hashes.py <GTAKeys.cs> <out.inc>"""
import re, sys

src = open(sys.argv[1], encoding="utf-8-sig").read()

def block(name):
    m = re.search(r"public static byte\[\](?:\[\])? " + name + r"\s*=\s*new byte\[[^\]]*\](?:\[\])?\s*\{", src)
    start = m.end()
    depth = 1
    i = start
    while depth:
        c = src[i]
        if c == "{": depth += 1
        elif c == "}": depth -= 1
        i += 1
    return src[start:i - 1]

def hashes(name):
    body = block(name)
    out = []
    for arr in re.findall(r"\{([^{}]*)\}", body):
        out.append([int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", arr)])
    return out

def single(name):
    return [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", block(name))]

aes = single("PC_AES_KEY_HASH")
ng = hashes("PC_NG_KEY_HASHES")
tab = hashes("PC_NG_DECRYPT_TABLE_HASHES")
lut = single("PC_LUT_HASH")
assert len(aes) == 20 and len(ng) == 101 and len(tab) == 272 and len(lut) == 20, (len(aes), len(ng), len(tab), len(lut))
assert all(len(h) == 20 for h in ng + tab)

def row(h): return "{" + ",".join("0x%02X" % b for b in h) + "}"
with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/gen_rpf_hashes.py from CodeWalker's GTAKeys.cs. SHA1 hashes only: there is no key in this file.\n")
    f.write("static const uint8_t kAesKeyHash[20] = %s;\n" % row(aes))
    f.write("static const uint8_t kHashLutHash[20] = %s;\n" % row(lut))
    f.write("static const uint8_t kNgKeyHashes[101][20] = {\n" + ",\n".join(row(h) for h in ng) + "};\n")
    f.write("static const uint8_t kNgTableHashes[272][20] = {\n" + ",\n".join(row(h) for h in tab) + "};\n")
