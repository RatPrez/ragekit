#!/usr/bin/env python3
"""Generates src/meta_tables.inc: the structure and enum info tables CodeWalker keeps in
MetaTypes.GetStructureInfo / GetEnumInfo, as plain C++ data.

    python tools/gen_meta_tables.py <CodeWalker.Core/GameFiles/MetaTypes> > src/meta_tables.inc

Names are resolved through MetaNames.cs (the MetaName enum is the joaat hash itself), so the
output has numbers only. Re-run it when CodeWalker's tables change.
"""
import re
import sys

root = sys.argv[1]
names_src = open(root + "/MetaNames.cs", encoding="utf-8-sig").read()
types_src = open(root + "/MetaTypes.cs", encoding="utf-8-sig").read()

name_map = {}
start = names_src.index("public enum MetaName : uint")
for m in re.finditer(r"^\s*(\w+)\s*=\s*(\d+)\s*,", names_src[start:], re.M):
    name_map[m.group(1)] = int(m.group(2))

DATA_TYPES = {
    "Boolean": 0x01, "SignedByte": 0x10, "UnsignedByte": 0x11, "SignedShort": 0x12, "UnsignedShort": 0x13,
    "SignedInt": 0x14, "UnsignedInt": 0x15, "Float": 0x21, "Float_XYZ": 0x33, "Float_XYZW": 0x34,
    "ByteEnum": 0x60, "IntEnum": 0x62, "ShortFlags": 0x64, "IntFlags1": 0x63, "IntFlags2": 0x65,
    "Hash": 0x4A, "Array": 0x52, "ArrayOfChars": 0x40, "ArrayOfBytes": 0x50, "DataBlockPointer": 0x59,
    "CharPointer": 0x44, "StructurePointer": 0x07, "Structure": 0x05,
}


def resolve(expr):
    expr = expr.strip()
    if expr == "0":
        return 0
    m = re.fullmatch(r"\(MetaName\)MetaTypeName\.(\w+)", expr)
    if m:
        return {"VECTOR4": 0x33, "HASH": 0x4a, "STRING": 0x10, "POINTER": 7, "USHORT": 0x13, "UINT": 0x15,
                "ARRAYINFO": 0x100, "BYTE": 17, "FLOAT": 33, "PsoPOINTER": 12}[m.group(1)]
    m = re.fullmatch(r"\(MetaName\)(\d+)", expr)
    if m:
        return int(m.group(1))
    m = re.fullmatch(r"MetaName\.(\w+)", expr)
    if m:
        return name_map[m.group(1)]
    raise ValueError("cannot resolve " + expr)


def region(src, fn):
    i = src.index("public static " + fn)
    j = src.index("default:", i)
    return src[i:j]


structs = []
sreg = region(types_src, "MetaStructureInfo GetStructureInfo")
sreg = re.sub(r"//.*", "", sreg)  # drop commented-out alternatives
for m in re.finditer(r"return new MetaStructureInfo\(([^,]+), (\d+), (\d+), (\d+),(.*?)\);\s*(?=case|\Z)", sreg, re.S):
    name = resolve(m.group(1))
    entries = []
    for e in re.finditer(r"new MetaStructureEntryInfo_s\(([^,]+(?:\)[^,]*)?), (-?\d+), MetaStructureEntryDataType\.(\w+), (\d+), (-?\d+), ([^\n]+?)\)\s*,?\s*$", m.group(5), re.M):
        entries.append((resolve(e.group(1)), int(e.group(2)), DATA_TYPES[e.group(3)], int(e.group(4)), int(e.group(5)), resolve(e.group(6))))
    structs.append((name, int(m.group(2)), int(m.group(3)), int(m.group(4)), entries))

enums = []
ereg = region(types_src, "MetaEnumInfo GetEnumInfo")
ereg = re.sub(r"//.*", "", ereg)
for m in re.finditer(r"return new MetaEnumInfo\(([^,]+), (\d+),(.*?)\);\s*(?=case|\Z)", ereg, re.S):
    name = resolve(m.group(1))
    entries = []
    for e in re.finditer(r"new MetaEnumEntryInfo_s\(([^,]+), (-?\d+)\)", m.group(3)):
        entries.append((resolve(e.group(1)), int(e.group(2))))
    enums.append((name, int(m.group(2)), entries))

# the MetaEnumInfo/StructureInfo default unknowns: struct Unknown_8h comes from the table
out = []
out.append("// Generated by tools/gen_meta_tables.py from CodeWalker's MetaTypes.cs. Do not edit.")
out.append("// %d structure infos, %d enum infos." % (len(structs), len(enums)))
out.append("static const GenEntry kGenEntries[] = {")
first = {}
idx = 0
for s in structs:
    first[s[0], s[1]] = idx
    for e in s[4]:
        out.append("    {%du, %d, %d, %d, %d, %du}," % (e[0], e[1], e[2], e[3], e[4], e[5]))
        idx += 1
out.append("};")
out.append("static const GenStruct kGenStructs[] = {")
for s in structs:
    out.append("    {%du, %du, %du, %d, %d, %d}," % (s[0], s[1], s[2], s[3], first[s[0], s[1]], len(s[4])))
out.append("};")
out.append("static const GenEnumEntry kGenEnumEntries[] = {")
eidx = 0
efirst = {}
for en in enums:
    efirst[en[0], en[1]] = eidx
    for e in en[2]:
        out.append("    {%du, %d}," % (e[0], e[1]))
        eidx += 1
out.append("};")
out.append("static const GenEnum kGenEnums[] = {")
for en in enums:
    out.append("    {%du, %du, %d, %d}," % (en[0], en[1], efirst[en[0], en[1]], len(en[2])))
out.append("};")
print("\n".join(out))
sys.stderr.write("structs %d enums %d entries %d\n" % (len(structs), len(enums), idx))
