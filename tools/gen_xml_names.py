#!/usr/bin/env python3
"""Generates src/xml_names.inc for xml.cpp.

  xml_param_names.inc : shader parameter hash -> name, exactly as CodeWalker's ShaderParamNames enum
                        prints it (`oracle xmlnames <out.inc>` dumps it from CodeWalker.Core).
  xml_shader_names.inc: shader name / .sps file name hashes, from CodeWalker's ShadersGen9Conversion.xml
                        (JenkIndex knows these in CodeWalker once a game folder has been scanned).

usage: gen_xml_names.py <ShadersGen9Conversion.xml> <out src dir>
"""
import sys, xml.etree.ElementTree as ET

def joaat(s):
    h = 0
    for ch in s.lower().encode('utf-8'):
        h = (h + ch) & 0xFFFFFFFF
        h = (h + (h << 10)) & 0xFFFFFFFF
        h ^= h >> 6
    h = (h + (h << 3)) & 0xFFFFFFFF
    h ^= h >> 11
    h = (h + (h << 15)) & 0xFFFFFFFF
    return h

root = ET.parse(sys.argv[1]).getroot()
names = {}
for it in root.findall('Item'):
    for tag in ('Name', 'FileName'):
        e = it.find(tag)
        if e is not None and e.text:
            names[joaat(e.text)] = e.text
with open(sys.argv[2] + '/xml_shader_names.inc', 'w') as f:
    f.write('// generated by tools/gen_xml_names.py from ShadersGen9Conversion.xml: do not edit\n')
    for h in sorted(names):
        f.write('{0x%08X, "%s"},\n' % (h, names[h]))
print(len(names), 'shader names')
