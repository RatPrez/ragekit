#!/usr/bin/env python3
"""Generates src/material_names.inc: the collision material names of the game's materials.dat, by index, the table
material_name() falls back on without an install.

    rk pull materials.dat <dir>
    python tools/gen_material_names.py <dir>/materials.dat src/material_names.inc
"""
import sys

lines = open(sys.argv[1], encoding="latin-1").read().splitlines()
names = []
for line in lines[1:]:   # the first line is the version
    t = line.split()
    if not t or t[0].startswith("#"):
        continue
    names.append(t[0])
out = ["// The collision material names of materials.dat (common.rpf/data/materials), by index: generated by",
       "// tools/gen_material_names.py from the Legacy install (version 12.00, both editions carry the same %d)." % len(names)]
row = ""
for n in names:
    item = '"%s",' % n
    if len(row) + len(item) + 1 > 120:
        out.append(row.rstrip())
        row = ""
    row += item + " "
if row:
    out.append(row.rstrip())
open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
print(len(names), "materials")
